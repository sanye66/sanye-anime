const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const { createRequire } = require('node:module')
const clientRequire = createRequire(path.resolve(__dirname, '../sanye_client/package.json'))
const ts = clientRequire('typescript')
const source = fs.readFileSync(path.resolve(__dirname, '../sanye_client/src/platform/android/experience.ts'), 'utf8')
function load(saved = '[]') {
  let now = 0
  const writes = new Map()
  const exports = {}
  vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, {
    exports, require: () => ({ ref: value => ({ value }) }), Date, URL,
    performance: { now: () => now }, localStorage: { getItem: () => saved, setItem: (key, value) => writes.set(key, value), removeItem: key => writes.delete(key) },
  })
  return { api: exports, advance: seconds => { now += seconds * 1000 }, writes }
}
test('来源观测隔离规则且不落盘网址及规则正文', () => {
  const { api, writes } = load()
  const key = api.healthKey('https://source.example/private?q=secret', { content: 'private-rule', sourceIndex: 0 })
  assert.notEqual(key, api.healthKey('https://source.example/private', { content: 'private-rule', sourceIndex: 1 }))
  assert.notEqual(key, api.healthKey('https://source.example/private', { content: 'other-rule', sourceIndex: 0 }))
  api.recordPlaybackSample(key, { started: true, failed: false, firstFrameMs: 100, watchedSeconds: 12, stallSeconds: 0 })
  const persisted = [...writes.values()].join('')
  assert.ok(!persisted.includes('private') && !persisted.includes('source.example'))
  assert.equal(api.sourcePlaybackHealth(key).score, null)
})
test('真实前进才计观看，暂停、拖动及长时间后台不计入成功', () => {
  const { api, advance } = load()
  const key = api.healthKey('https://source.example')
  const observation = api.createPlaybackObservation(key)
  observation.tick(0, true, false)
  advance(1); observation.tick(40, true, true)
  advance(60); observation.tick(100, true, false)
  observation.pause(); advance(60); observation.tick(101, false, false)
  observation.finish(); observation.failure(); observation.firstFrame()
  assert.equal(api.sourcePlaybackHealth(key), null)
  assert.equal(api.experienceEvents.value.length, 0)
})
test('卡顿只在实际恢复后结束，失败与完成幂等', () => {
  const { api, advance } = load()
  const key = api.healthKey('https://source.example')
  const observation = api.createPlaybackObservation(key)
  observation.firstFrame(); observation.tick(0, true, false); observation.waiting()
  advance(1); observation.tick(0, true, false)
  advance(1); observation.tick(0, true, false)
  assert.equal(api.experienceEvents.value.filter(event => event.stage === 'stall').length, 0)
  advance(1); observation.tick(1, true, false)
  assert.equal(api.experienceEvents.value.find(event => event.stage === 'stall').milliseconds, 3000)
  observation.failure(); observation.finish(); observation.finish()
  assert.equal(api.sourcePlaybackHealth(key).samples, 1)
  assert.equal(api.experienceEvents.value.filter(event => event.stage === 'playback').length, 1)
})
test('破损和未来统计不会污染来源评分', () => {
  const { api } = load(JSON.stringify([['bad', [null]], ['abc-def', [{ at: Date.now() + 60000, started: true, failed: false, firstFrameMs: 1, watchedSeconds: 20, stallSeconds: 0 }]]]))
  assert.equal(api.sourcePlaybackHealth('abc-def'), null)
})
test('诊断脱敏保留错误码和主机，不包含路径、参数、规则或非法错误内容', () => {
  const { api } = load()
  api.recordExperience('playback', 'failed', 200, 'https://cdn.example.org/private/movie?token=secret', undefined, { engine: 'media3', code: 'ERROR_CODE_IO_NETWORK_CONNECTION_FAILED' })
  api.recordExperience('playback', 'failed', Infinity, 'file:///data/user/private', undefined, { engine: 'media3', code: 'https://private.example/secret' })
  const report = JSON.stringify(api.experienceEvents.value)
  assert.equal(api.experienceEvents.value[0].source, 'cdn.example.org')
  assert.equal(api.experienceEvents.value[0].code, 'ERROR_CODE_IO_NETWORK_CONNECTION_FAILED')
  assert.equal(api.experienceEvents.value[1].code, undefined)
  assert.equal(api.experienceEvents.value[1].source, '')
  assert.equal(api.experienceEvents.value[1].milliseconds, 0)
  assert.equal(/secret|private|token/.test(report), false)
  for (let index = 0; index < 150; index++) api.recordExperience('search', 'success', index)
  assert.equal(api.experienceEvents.value.length, 100)
})
test('视频性能仅保留有效实测字段，不把片源帧率冒充刷新率，不包含地址或额外原生内容', () => {
  const { api } = load()
  api.recordNativePerformance({ width: 1920, height: 1080, fps: 23.976, bitrate: 2500000, droppedFrames: 4, seekLatencyMs: 180, decoder: 'c2.android.avc.decoder', privateUrl: 'https://example.org/secret' })
  assert.equal(api.nativePerformance.value.fps, 23.976)
  assert.equal(api.nativePerformance.value.droppedFrames, 4)
  assert.equal(JSON.stringify(api.nativePerformance.value).includes('secret'), false)
  api.recordNativePerformance({ fps: Infinity, width: -1, height: 1e9, decoder: 'https://secret', droppedFrames: 0 })
  assert.equal(api.nativePerformance.value.fps, undefined)
  assert.equal(api.nativePerformance.value.decoder, undefined)
  assert.equal(api.nativePerformance.value.droppedFrames, 0)
  api.clearExperience(); assert.equal(api.nativePerformance.value, undefined)
})
